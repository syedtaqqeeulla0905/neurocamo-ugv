class VirtualActuator:
    def __init__(self):
        self.command = "PATROL SCAN"
        self.command_detail = "Perimeter Clear - Radar Sweep"
        self.pwm_a = 0
        self.pwm_b = 0
        self.bearing_deg = 0.0
        self.packet_log = deque(maxlen=4)
        self.seq = 1000

    def update(self, detected: bool, bbox_norm, conf: float, snn_watts: float):
        timestamp = datetime.now().strftime("%H:%M:%S.%f")[:-3]
        self.seq += 1

        if not detected or bbox_norm is None or conf < 0.25:
            self.command = "PATROL SCAN"
            self.command_detail = "Perimeter Clear - Radar Sweep"
            self.pwm_a = 0
            self.pwm_b = 0
            self.bearing_deg = 0.0
            pkt = f"[{timestamp}] UART_TX: $UGV,SEQ:{self.seq:05d},CMD:STDBY,M1:000,M2:000,BRG:+00.0,PWR:{snn_watts:.2f}W*00"
            self.packet_log.appendleft(pkt)
            return

        xc, yc, bw, bh = bbox_norm
        offset = xc - 0.5
        self.bearing_deg = offset * 110.0

        if abs(offset) < 0.10:
            self.command = "ENGAGE FORWARD"
            self.command_detail = f"Target Locked | Bearing {self.bearing_deg:+.0f} deg"
            self.pwm_a = 230
            self.pwm_b = 230
            cmd_tag = "ENGAGE_FWD"
        elif offset < -0.10:
            steer = min(abs(offset) * 2.0, 1.0)
            self.command = "STEER LEFT"
            self.command_detail = f"Bearing {self.bearing_deg:+.0f} deg"
            self.pwm_a = int(80 + (1 - steer) * 120)
            self.pwm_b = 230
            cmd_tag = "STEER_LEFT"
        else:
            steer = min(abs(offset) * 2.0, 1.0)
            self.command = "STEER RIGHT"
            self.command_detail = f"Bearing {self.bearing_deg:+.0f} deg"
            self.pwm_a = 230
            self.pwm_b = int(80 + (1 - steer) * 120)
            cmd_tag = "STEER_RIGHT"

        pkt = f"[{timestamp}] UART_TX: $UGV,SEQ:{self.seq:05d},CMD:{cmd_tag},M1:{self.pwm_a:03d},M2:{self.pwm_b:03d},BRG:{self.bearing_deg:+05.1f},PWR:{snn_watts:.2f}W*1A"
        self.packet_log.appendleft(pkt)


