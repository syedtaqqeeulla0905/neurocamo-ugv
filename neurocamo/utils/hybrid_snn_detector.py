    cv2.putText(canvas, stat_txt, (815, 26), cv2.FONT_HERSHEY_SIMPLEX, 0.40, stat_col, 1, cv2.LINE_AA)

    cv2.putText(canvas, f"JETSON FPS: {fps:.0f} | LATENCY: {lat_ms:.1f}ms", (1050, 26),
                cv2.FONT_HERSHEY_SIMPLEX, 0.40, COL_WHITE, 1, cv2.LINE_AA)

    # 2. Main Camera Feed (X: 16, Y: 50, W: 740, H: 460)
    FEED_W, FEED_H = 740, 460
    feed_view = cv2.resize(frame, (FEED_W, FEED_H))

    if detected:
        bbox = out.get("bbox_norm", [0.5, 0.5, 0.2, 0.2])
        xc, yc, bw, bh = bbox
        x1 = max(0, int((xc - bw / 2.0) * FEED_W))
        y1 = max(0, int((yc - bh / 2.0) * FEED_H))
        x2 = min(FEED_W - 1, int((xc + bw / 2.0) * FEED_W))
        y2 = min(FEED_H - 1, int((yc + bh / 2.0) * FEED_H))

        cv2.rectangle(feed_view, (x1, y1), (x2, y2), COL_GREEN, 2)
        blen = max(10, min((x2 - x1) // 4, (y2 - y1) // 4))
        for cx_b, cy_b in [(x1, y1), (x2, y1), (x1, y2), (x2, y2)]:
            dx = blen if cx_b == x1 else -blen
            dy = blen if cy_b == y1 else -blen
