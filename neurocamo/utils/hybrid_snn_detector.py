def main():
    global upload_requested

    print("\n" + "="*75)
    print("  NEUROCAMO: SNN Tactical Ground Control Station")
    print("  Engine: Biological ALIF Neurons + Dense-Mask Head (v4)")
    print("="*75)

    print("  [1/2] Loading SNN Model Bundle...")
    bundle = inference.ModelBundle()
    actuator = VirtualActuator()

    p_dir = os.path.join(os.path.dirname(ROOT), "test_image")
    frames = []
    for ext in ["*.jpg", "*.jpeg", "*.png", "*.webp"]:
        frames.extend(glob.glob(os.path.join(p_dir, ext)))
    frames.sort()
    img_idx = 0

    print(f"  [2/2] Found {len(frames)} verified test samples.")
    print("  [HOTKEY] Press 'U' anytime to open Windows file picker and test YOUR images!\n")

    win_name = "NeuroCamo - SNN Defense System"
    cv2.namedWindow(win_name, cv2.WINDOW_AUTOSIZE)
    cv2.setMouseCallback(win_name, mouse_callback)

    prev_t = time.time()
    paused = False
    custom_frame = None
    custom_name = ""

    while True:
        if upload_requested:
            upload_requested = False
            picked = pick_image_file()
            if picked and os.path.exists(picked):
                img = cv2.imread(picked)
                if img is not None:
                    custom_frame = img
                    custom_name = os.path.basename(picked)
                    paused = True
                    print(f"  [UPLOAD] Loaded custom image: {custom_name}")

        if custom_frame is not None:
            frame = custom_frame
            cur_name = f"[CUSTOM] {custom_name}"
        else:
            frame = cv2.imread(frames[img_idx])
            cur_name = os.path.basename(frames[img_idx])
            if not paused:
                time.sleep(1.2)
                img_idx = (img_idx + 1) % len(frames)

        t0 = time.time()

        # Run Official SNN Inference
        out = inference.run_inference(bundle, frame)

        t1 = time.time()
        lat_ms = (t1 - t0) * 1000
        fps = 1.0 / (t1 - prev_t + 1e-6)
        prev_t = t1

        # Render HUD
        canvas, snn_watts = draw_hud(frame, out, actuator, fps, lat_ms, cur_name)

        # Update Actuator & UART Packet Stream
        detected = out.get("bbox_drawn", False)
        bbox = out.get("bbox_norm")
        conf = out.get("confidence", 0.0)
        actuator.update(detected, bbox, conf, snn_watts)

        cv2.imshow(win_name, canvas)

        key = cv2.waitKey(1) & 0xFF
        if key == ord('q') or key == 27:
            break
        elif key == ord(' '):
            paused = not paused
        elif key == ord('u') or key == ord('U'):
            upload_requested = True
        elif key == ord('r') or key == ord('R'):
            custom_frame = None  # Reset to slideshow
            paused = False
            print("  [RESET] Resumed automated test suite.")
        elif key == ord('n') or key == ord('.'):
            custom_frame = None
            img_idx = (img_idx + 1) % len(frames)
        elif key == ord('s'):
            fname = f"e:/major_project/neurocamo_gcs_{datetime.now().strftime('%H%M%S')}.png"
            cv2.imwrite(fname, canvas)
            print(f"  [SAVED] Screenshot: {fname}")

    cv2.destroyAllWindows()
    print("  System closed.\n")


if __name__ == "__main__":
    main()
