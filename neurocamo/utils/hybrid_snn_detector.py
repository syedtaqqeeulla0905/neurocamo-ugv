    cv2.putText(canvas, "NEUROCAMO", (16, 28), cv2.FONT_HERSHEY_SIMPLEX, 0.7, COL_CYAN, 2, cv2.LINE_AA)

    verdict = out.get("verdict", "NO CAMO DETECTED")
    conf = out.get("confidence", 0.0)
    detected = out.get("bbox_drawn", False)

