upload_requested = False

def mouse_callback(event, x, y, flags, param):
    global upload_requested
    if event == cv2.EVENT_LBUTTONDOWN:
        # Check if clicked inside "[U] UPLOAD IMAGE" button (X: 586-746, Y: 60-84)
        if 586 <= x <= 746 and 60 <= y <= 84:
            upload_requested = True


def pick_image_file():
    root = tk.Tk()
    root.withdraw()
    root.attributes('-topmost', True)
    fpath = filedialog.askopenfilename(
        title="Select Camouflage Image for NeuroCamo SNN Analysis",
        filetypes=[("Image files", "*.jpg;*.jpeg;*.png;*.webp;*.bmp"), ("All files", "*.*")]
    )
    root.destroy()
    return fpath


